// Turns the eval corpora in packages/TimbreKit/Fixtures and
// packages/TimbreCore/Fixtures into src/lib/evals/cases.json, so Backstage
// can show every case and every check without a Swift toolchain. Same
// arrangement as sync-decisions.mjs: the fixtures are the source of truth,
// the JSON is committed, CI fails on drift. What the cases *measured* is a
// separate file written by measure-evals.mjs on a Mac.
//
// Usage: pnpm run sync:evals

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fixtures = process.env.FIXTURES_DIR ?? resolve(here, '../../packages/TimbreKit/Fixtures');
const core = process.env.CORE_FIXTURES_DIR ?? resolve(here, '../../packages/TimbreCore/Fixtures');
const out = process.env.EVALS_OUT ?? resolve(here, '../src/lib/evals/cases.json');

const read = (dir, name) => JSON.parse(readFileSync(resolve(dir, name), 'utf8'));

const corpus = read(fixtures, 'corpus.json');
const commands = read(fixtures, 'commands.json');
// The learning corpora (GDR-0023, GDR-0027): deterministic checks in
// TimbreCore, the example writer and the judge where the model is.
const examples = read(fixtures, 'examples.json');
const spell = read(core, 'spell.json');
const picks = read(core, 'picks.json');
const drills = read(core, 'drills.json');

const polisher = corpus.cases.map((c) => ({
	id: c.id,
	note: c.note ?? '',
	transcript: c.transcript,
	spoken: c.spoken ?? null,
	appContext: c.appContext ?? null,
	required: c.required ?? [],
	forbidden: c.forbidden ?? [],
	requiresPunctuation: c.requiresPunctuation ?? false,
	requiresLineBreak: c.requiresLineBreak ?? false,
	vocabulary: c.vocabulary ?? [],
	corrections: c.corrections ?? []
}));

const verbs = commands.cases.map((c) => ({
	id: c.id,
	command: c.command,
	note: c.note ?? '',
	text: c.text,
	required: c.required ?? [],
	forbidden: c.forbidden ?? [],
	exact: c.exact ?? null,
	vocabulary: c.vocabulary ?? [],
	corrections: c.corrections ?? [],
	acronyms: c.acronyms ?? []
}));

// One row per case: the input, and what must come of it. A deterministic
// corpus needs no measured run; a judged one is measured like the polisher.
const learning = [
	{
		id: 'spell',
		title: 'Spell it',
		path: 'packages/TimbreCore/Fixtures/spell.json',
		judged: false,
		cases: spell.cases.map((c) => ({
			id: c.id,
			note: c.note ?? '',
			input: `${c.word}: “${c.spoken}”`,
			expect: c.passes ? 'passes' : 'fails'
		}))
	},
	{
		id: 'picks',
		title: 'The word of the day',
		path: 'packages/TimbreCore/Fixtures/picks.json',
		judged: false,
		cases: picks.cases.map((c) => ({
			id: c.id,
			note: c.note ?? '',
			input: `${c.entries.length} entries, ${c.events.length} events, on ${c.day}`,
			expect: c.expect.term ? `${c.expect.source}: ${c.expect.term}` : c.expect.source
		}))
	},
	{
		id: 'drills',
		title: 'The drills',
		path: 'packages/TimbreCore/Fixtures/drills.json',
		judged: true,
		cases: drills.cases.map((c) => ({
			id: c.id,
			note: c.note ?? '',
			input: `${c.drill} · ${c.term}: “${c.spoken}”`,
			expect: c.judge ? `${c.expect}, then the judge says ${c.judge}` : c.expect
		}))
	},
	{
		id: 'examples',
		title: 'The example writer',
		path: 'packages/TimbreKit/Fixtures/examples.json',
		judged: true,
		cases: examples.cases.map((c) => ({
			id: c.id,
			note: c.note ?? '',
			input: c.industry ? `${c.term} · ${c.industry}` : c.term,
			expect: 'a sentence that passes the guardrail'
		}))
	}
];

const data = {
	polisher: { path: 'packages/TimbreKit/Fixtures/corpus.json', cases: polisher },
	commands: { path: 'packages/TimbreKit/Fixtures/commands.json', cases: verbs },
	learning,
	// One audio fixture per polisher case, generated by tools/make-audio-fixtures.sh
	// and gitignored, so the count is the corpus's by construction.
	audio: { path: 'packages/TimbreKit/Fixtures/audio', cases: polisher.length }
};

writeFileSync(out, JSON.stringify(data, null, '\t') + '\n');
const learningCount = learning.reduce((n, l) => n + l.cases.length, 0);
console.log(
	`${polisher.length} polisher + ${verbs.length} command + ${learningCount} learning cases → ${out.replace(resolve(here, '..') + '/', '')}`
);
