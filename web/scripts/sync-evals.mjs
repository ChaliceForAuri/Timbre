// Turns the eval corpora in packages/TimbreKit/Fixtures into
// src/lib/evals/cases.json, so Backstage can show every case and every
// check without a Swift toolchain. Same arrangement as sync-decisions.mjs:
// the fixtures are the source of truth, the JSON is committed, CI fails on
// drift. What the cases *measured* is a separate file written by
// measure-evals.mjs on a Mac.
//
// Usage: pnpm run sync:evals

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fixtures = process.env.FIXTURES_DIR ?? resolve(here, '../../packages/TimbreKit/Fixtures');
const out = process.env.EVALS_OUT ?? resolve(here, '../src/lib/evals/cases.json');

const corpus = JSON.parse(readFileSync(resolve(fixtures, 'corpus.json'), 'utf8'));
const commands = JSON.parse(readFileSync(resolve(fixtures, 'commands.json'), 'utf8'));

const polisher = corpus.cases.map((c) => ({
	id: c.id,
	note: c.note ?? '',
	transcript: c.transcript,
	spoken: c.spoken ?? null,
	appContext: c.appContext ?? null,
	required: c.required ?? [],
	forbidden: c.forbidden ?? [],
	requiresPunctuation: c.requiresPunctuation ?? false,
	requiresLineBreak: c.requiresLineBreak ?? false,
	vocabulary: c.vocabulary ?? [],
	corrections: c.corrections ?? []
}));

const verbs = commands.cases.map((c) => ({
	id: c.id,
	command: c.command,
	note: c.note ?? '',
	text: c.text,
	required: c.required ?? [],
	forbidden: c.forbidden ?? [],
	exact: c.exact ?? null,
	vocabulary: c.vocabulary ?? [],
	corrections: c.corrections ?? [],
	acronyms: c.acronyms ?? []
}));

const data = {
	polisher: { path: 'packages/TimbreKit/Fixtures/corpus.json', cases: polisher },
	commands: { path: 'packages/TimbreKit/Fixtures/commands.json', cases: verbs },
	// One audio fixture per polisher case, generated by tools/make-audio-fixtures.sh
	// and gitignored, so the count is the corpus's by construction.
	audio: { path: 'packages/TimbreKit/Fixtures/audio', cases: polisher.length }
};

writeFileSync(out, JSON.stringify(data, null, '\t') + '\n');
console.log(`${polisher.length} polisher + ${verbs.length} command cases → ${out.replace(resolve(here, '..') + '/', '')}`);
